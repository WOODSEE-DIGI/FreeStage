#!/bin/zsh
#
# setup-debug-signing.sh
#
# Imports a self-signed code-signing identity for FreeStage Debug builds.
# A stable identity means macOS Screen Recording (and Camera/Microphone) TCC
# grants survive across Xcode rebuilds. Ad-hoc signing gets a new cdhash on
# every build, which invalidates the grant even though System Settings still
# shows FreeStage as enabled.
#
# Run once per machine in a normal Terminal window (not over plain SSH):
#   ./scripts/setup-debug-signing.sh
#
# The certificate is stored as a PKCS#12 at ~/.freestage/FreeStageDebug.p12
# with the local password "freestagedebug". It is imported into your login
# keychain. The identity is not an Apple-issued developer certificate.
#

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")/.." && pwd)"
KEYCHAIN_DIR="$HOME/.freestage"
P12_PATH="$KEYCHAIN_DIR/FreeStageDebug.p12"
P12_PASSWORD="freestagedebug"
CERT_NAME="FreeStage Debug"
XCCONFIG_PATH="$REPO_ROOT/Resources/DebugCodeSigningLocal.xcconfig"
LOGIN_KEYCHAIN="$HOME/Library/Keychains/login.keychain-db"

mkdir -p "$KEYCHAIN_DIR"

# Generate the self-signed certificate if it has not been created yet.
if [[ ! -f "$P12_PATH" ]]; then
    echo "Generating self-signed code-signing certificate '$CERT_NAME' ..."
    KEY_PATH="$KEYCHAIN_DIR/FreeStageDebug.key"
    CRT_PATH="$KEYCHAIN_DIR/FreeStageDebug.crt"

    openssl req -x509 -newkey rsa:2048 \
        -keyout "$KEY_PATH" \
        -out "$CRT_PATH" \
        -days 3650 \
        -nodes \
        -subj "/CN=$CERT_NAME/O=FreeStage/C=US" \
        -addext "basicConstraints=CA:FALSE" \
        -addext "keyUsage=digitalSignature" \
        -addext "extendedKeyUsage=codeSigning" \
        -addext "subjectKeyIdentifier=hash"

    openssl pkcs12 -export \
        -out "$P12_PATH" \
        -inkey "$KEY_PATH" \
        -in "$CRT_PATH" \
        -name "$CERT_NAME" \
        -passout pass:"$P12_PASSWORD" \
        -certpbe PBE-SHA1-3DES \
        -keypbe PBE-SHA1-3DES \
        -macalg SHA1

    rm -f "$KEY_PATH" "$CRT_PATH"
fi

# Make sure the login keychain is available for codesign.
security unlock-keychain "$LOGIN_KEYCHAIN" || true

# Import the identity if it is not already present.
if security find-identity -v -p codesigning "$LOGIN_KEYCHAIN" 2>/dev/null | grep -q "\"$CERT_NAME\""; then
    echo "Certificate '$CERT_NAME' already exists in the login keychain."
else
    echo "Importing '$CERT_NAME' into the login keychain ..."
    security import "$P12_PATH" -k "$LOGIN_KEYCHAIN" -P "$P12_PASSWORD" -T /usr/bin/codesign
fi

# Xcode rejects the certificate when selected by name, but accepts the SHA-1
# hash of the identity. Write that hash into an xcconfig that is used only for
# Debug builds. This file is gitignored so the per-machine hash is not tracked.
IDENTITY_HASH=$(security find-identity -v -p codesigning "$LOGIN_KEYCHAIN" 2>/dev/null \
    | grep "\"$CERT_NAME\"" \
    | head -1 \
    | awk '{print $2}')
if [[ -z "$IDENTITY_HASH" ]]; then
    echo "ERROR: Could not find '$CERT_NAME' in the login keychain."
    exit 1
fi

cat > "$XCCONFIG_PATH" <<EOF
// Generated by scripts/setup-debug-signing.sh. Do not edit by hand.
// This file is gitignored; run the setup script again if the certificate is
// regenerated.
CODE_SIGN_IDENTITY = $IDENTITY_HASH
EOF

echo ""
echo "Installed identity: $CERT_NAME ($IDENTITY_HASH)"
echo "Wrote Debug signing override to $XCCONFIG_PATH"
echo ""
echo "Debug signing setup complete. Build FreeStage Debug with:"
echo "  xcodegen generate && xcodebuild -project FreeStage.xcodeproj -scheme FreeStage -configuration Debug build"
